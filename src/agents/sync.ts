import { existsSync, lstatSync } from "node:fs";
import { mkdir, readdir, rm, symlink } from "node:fs/promises";
import { join } from "node:path";
import { stringify } from "yaml";
import type { AgentDef } from "./load.ts";

/*
 * .kanbot/agents/*.md is the single source of truth. This module renders it
 * into each CLI's native format so agents work both headless (driven by the
 * daemon) and in interactive sessions:
 *   Claude: .claude/agents/<name>.md + .claude/settings.json permissions
 *   Codex:  .codex/agents/<name>.toml
 * Skills live in .agents/skills (Codex native); .claude/skills symlinks to it.
 */

export const GENERATED =
	"generated by kanbot — edit .kanbot/agents/ and run `kanbot sync`";

const CLAUDE_TOOLS: Record<string, string[]> = {
	read: ["Read", "Grep", "Glob"],
	edit: ["Edit", "Write", "NotebookEdit"],
	bash: ["Bash"],
	web: ["WebFetch", "WebSearch"],
};

/** Agents never touch GitHub; the daemon owns all remote side effects. */
export const CLAUDE_DENY = [
	"Bash(gh *)",
	"Bash(git push *)",
	"Bash(git remote *)",
	"Bash(git config *)",
];

/** Agents act as the human's account: no Claude co-author trailers or PR footers. */
export const CLAUDE_ATTRIBUTION = {
	attribution: { commit: "", pr: "" },
	includeCoAuthoredBy: false,
};

export function claudeTools(agent: AgentDef): string[] {
	const tools = agent.tools.flatMap((t) => CLAUDE_TOOLS[t] ?? []);
	if (agent.skills.length) tools.push("Skill");
	if (agent.subagents.length) tools.push("Task");
	return [...new Set(tools)];
}

export function renderClaudeAgent(agent: AgentDef): string {
	const fm: Record<string, unknown> = {
		name: agent.name,
		description: agent.description,
		tools: claudeTools(agent).join(", "),
	};
	if (agent.models.claude) fm.model = agent.models.claude;
	if (agent.effort) fm.effort = agent.effort;
	if (agent.skills.length) fm.skills = agent.skills;
	return `---\n${stringify(fm).trim()}\n---\n<!-- ${GENERATED} -->\n\n${agentInstructions(agent)}\n`;
}

export function renderClaudeSettings(agents: AgentDef[]): string {
	const allow = [...new Set(agents.flatMap(claudeTools))].sort();
	return `${JSON.stringify(
		{
			$comment: GENERATED,
			permissions: { allow, deny: CLAUDE_DENY },
			...CLAUDE_ATTRIBUTION,
		},
		null,
		2,
	)}\n`;
}

const tomlString = (s: string) => JSON.stringify(s);

export function renderCodexAgent(agent: AgentDef): string {
	const lines = [
		`# ${GENERATED}`,
		`name = ${tomlString(agent.name)}`,
		`description = ${tomlString(agent.description)}`,
	];
	if (agent.models.codex && agent.models.codex !== "default") {
		lines.push(`model = ${tomlString(agent.models.codex)}`);
	}
	if (agent.effort) {
		const effort = agent.effort === "max" ? "xhigh" : agent.effort;
		lines.push(`model_reasoning_effort = ${tomlString(effort)}`);
	}
	lines.push(
		`developer_instructions = ${tomlString(agentInstructions(agent))}`,
	);
	return `${lines.join("\n")}\n`;
}

/**
 * Body plus the parts of the frontmatter that a CLI can't express natively, so
 * the agent knows which skills and helpers it is expected to use.
 */
export function agentInstructions(agent: AgentDef): string {
	const extra: string[] = [];
	if (agent.skills.length) {
		extra.push(
			`Skills to load when relevant: ${agent.skills.map((s) => `\`${s}\``).join(", ")}.`,
		);
	}
	if (agent.subagents.length) {
		extra.push(
			`Subagents you can delegate to: ${agent.subagents.map((s) => `\`${s}\``).join(", ")}. Delegate focused, independent work to them; keep the final decisions yourself.`,
		);
	}
	return extra.length
		? `${agent.body}\n\n## Toolbox\n\n${extra.join("\n")}`
		: agent.body;
}

export type SyncFile = { path: string; content: string };

export function renderAll(agents: AgentDef[]): SyncFile[] {
	return [
		...agents.map((a) => ({
			path: join(".claude", "agents", `${a.name}.md`),
			content: renderClaudeAgent(a),
		})),
		{
			path: join(".claude", "settings.json"),
			content: renderClaudeSettings(agents),
		},
		...agents.map((a) => ({
			path: join(".codex", "agents", `${a.name}.toml`),
			content: renderCodexAgent(a),
		})),
	];
}

/** Writes generated files. Returns paths whose content changed. */
export async function sync(
	root: string,
	agents: AgentDef[],
	{ check = false } = {},
): Promise<string[]> {
	const files = renderAll(agents);
	const changed: string[] = [];
	for (const f of files) {
		const abs = join(root, f.path);
		const existing = existsSync(abs) ? await Bun.file(abs).text() : null;
		if (existing === f.content) continue;
		changed.push(f.path);
		if (!check) await Bun.write(abs, f.content);
	}
	// Remove generated agents whose source was deleted.
	const keep = new Set(files.map((f) => f.path));
	for (const [dir, ext] of [
		[join(".claude", "agents"), ".md"],
		[join(".codex", "agents"), ".toml"],
	] as const) {
		const abs = join(root, dir);
		if (!existsSync(abs)) continue;
		for (const name of await readdir(abs)) {
			const rel = join(dir, name);
			if (!name.endsWith(ext) || keep.has(rel)) continue;
			const text = await Bun.file(join(abs, name)).text();
			if (!text.includes(GENERATED)) continue;
			changed.push(rel);
			if (!check) await rm(join(abs, name));
		}
	}
	if (!(await linkSkills(root, check))) changed.push(join(".claude", "skills"));
	return changed;
}

/** Ensure .claude/skills -> ../.agents/skills. Returns true when already correct. */
async function linkSkills(root: string, check: boolean) {
	const link = join(root, ".claude", "skills");
	const ok = existsSync(link) && lstatSync(link).isSymbolicLink();
	if (ok || check) return ok;
	if (existsSync(link)) {
		throw new Error(
			".claude/skills exists and is not a symlink. Move its skills into .agents/skills.",
		);
	}
	await mkdir(join(root, ".agents", "skills"), { recursive: true });
	await mkdir(join(root, ".claude"), { recursive: true });
	await symlink(join("..", ".agents", "skills"), link);
	return false;
}
